import {test,expect} from '@playwright/test'
test.describe('LUMEN golden master',()=>{
 test.beforeEach(async({page})=>{await page.goto('/?vnext=1')})
 test('personal flow reaches identity boundary',async({page})=>{
  await expect(page.getByRole('heading',{name:'Una vida más tuya.'})).toBeVisible()
  await page.getByText('Cuéntame en qué momento estás...').click()
  await expect(page.getByRole('heading',{name:'¿Qué estás viviendo hoy?'})).toBeVisible()
  await page.getByRole('button',{name:'Continuar'}).click()
  await expect(page.getByRole('dialog',{name:'Entrar a LUMEN'})).toBeVisible()
  await expect(page.getByLabel('Email')).toBeVisible()
 })
 test('canonical destinations stay reachable',async({page})=>{
  for(const x of ['Inicio','Explorar','Mi Vida','Comunidad','Biblioteca']) await expect(page.getByText(x,{exact:true})).toBeVisible()
  await page.getByText('Explorar',{exact:true}).click();await expect(page.getByRole('heading',{name:'Explorar el Territorio'})).toBeVisible()
  await page.getByText('Mi Vida',{exact:true}).click();await expect(page.getByRole('heading',{name:'Mi Mapa Vivo'})).toBeVisible()
  await page.getByText('Comunidad',{exact:true}).click();await expect(page.getByRole('heading',{name:'Impacto y Aprendizaje'})).toBeVisible()
  await page.getByText('Biblioteca',{exact:true}).click();await expect(page.getByRole('heading',{name:'Tu Constelación'})).toBeVisible()
 })
 test('public Source discovery reaches a real resource and protects personal return',async({page})=>{
  await page.getByText('Explorar',{exact:true}).click()
  await page.getByRole('button',{name:'Bienestar físico y mental'}).click()
  await expect(page.getByRole('heading',{name:'Tu Constelación'})).toBeVisible()
  const card=page.locator('.gm-resources>button').first()
  await expect(card).toBeVisible({timeout:10000})
  await card.click()
  await expect(page.locator('.experience h1').first()).toBeVisible()
  await page.getByRole('button',{name:'Marcar como realizada'}).click()
  await expect(page.getByRole('heading',{name:'¿Cómo fue?'})).toBeVisible()
  await page.getByRole('button',{name:'Guardar en mi Santuario'}).click()
  await expect(page.getByRole('dialog',{name:'Entrar a LUMEN'})).toBeVisible()
 })
 test('official audio remains attributed and returns with a neutral signal',async({page})=>{
  await page.getByText('Explorar',{exact:true}).click()
  await page.getByRole('button',{name:'Bienestar físico y mental'}).click()
  await expect(page.getByRole('heading',{name:'Tu Constelación'})).toBeVisible()
  await page.getByRole('button',{name:'Audios',exact:true}).click()
  await page.getByRole('button',{name:/Poner los pies en la tierra · audio OPS\/OMS/}).click()
  await expect(page.getByRole('link',{name:/Escuchar en OPS\/OMS Se abre en la fuente original/})).toHaveAttribute('href',/paho\.org/)
  await page.getByRole('button',{name:'Terminé de explorar'}).click()
  await expect(page.getByRole('heading',{name:'¿Cómo fue?'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Algo'})).toHaveClass(/on/)
  await page.getByRole('button',{name:'Guardar en mi Santuario'}).click()
  await expect(page.getByRole('dialog',{name:'Entrar a LUMEN'})).toBeVisible()
 })
 test('Faro editing protects persistence behind identity',async({page})=>{
  await page.getByText('Mi Vida',{exact:true}).click()
  await page.getByRole('button',{name:'Ver mi Faro'}).click()
  await page.getByRole('button',{name:'Editar mi Faro'}).click()
  await expect(page.locator('.gm-faro-main textarea')).toBeVisible()
  await page.getByRole('button',{name:'Guardar mi Faro'}).click()
  await expect(page.getByRole('dialog',{name:'Entrar a LUMEN'})).toBeVisible()
 })
 test('mobile has no horizontal overflow',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  const d=await page.evaluate(()=>({sw:document.documentElement.scrollWidth,cw:document.documentElement.clientWidth}))
  expect(d.sw).toBeLessThanOrEqual(d.cw)
 })
})
