import {test,expect} from '@playwright/test'
test.describe('LUMEN golden master',()=>{
 test.beforeEach(async({page})=>{await page.goto('/?vnext=1')})
 test('ten-screen approved flow is complete',async({page})=>{
  await expect(page.getByRole('heading',{name:'Una vida más tuya.'})).toBeVisible()
  await page.getByText('Cuéntame en qué momento estás...').click()
  await expect(page.getByRole('heading',{name:'¿Qué estás viviendo hoy?'})).toBeVisible()
  await expect(page.locator('textarea')).toContainText('Estoy agotado.')
  await page.getByRole('button',{name:'→'}).click()
  await expect(page.getByRole('heading',{name:'Mi Mapa Vivo'})).toBeVisible()
  for(const x of ['Dirección','Potencial','Condiciones','Realización']) await expect(page.getByText(x,{exact:true}).first()).toBeVisible()
  await page.getByRole('button',{name:'Ver mi Faro'}).click()
  await expect(page.getByRole('heading',{name:'Mi Faro'})).toBeVisible()
  await expect(page.getByText('Estar presente con mi familia, viviendo un trabajo significativo, cuidando mi bienestar.')).toBeVisible()
  await page.getByRole('button',{name:/Abrir una constelación/}).click()
  await expect(page.getByRole('heading',{name:'Tu Constelación'})).toBeVisible()
  for(const x of ['Todas','Prácticas','Lecturas','Audios','Experiencias']) await expect(page.getByRole('button',{name:x,exact:true})).toBeVisible()
  for(const x of ['Transición consciente trabajo-hogar','Lo que de verdad importa','Volver al presente','Ritual de conexión con tus hijos']) await expect(page.getByText(x,{exact:true})).toBeVisible()
  await page.getByRole('button',{name:/Ritual de conexión con tus hijos/}).click()
  await expect(page.getByRole('heading',{name:'Ritual de conexión con tus hijos'})).toBeVisible()
  await page.getByRole('button',{name:'Marcar como realizada'}).click()
  await expect(page.getByRole('heading',{name:'¿Cómo fue?'})).toBeVisible()
  for(const x of ['Me ayudó mucho','Me ayudó','Algo','No mucho','No me sirvió']) await expect(page.getByRole('button',{name:x,exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Guardar en mi Santuario'}).click()
  await expect(page.getByRole('heading',{name:'Mi Santuario'})).toBeVisible()
  for(const x of ['Ritual de conexión con tus hijos','Volver al presente','Lo que de verdad importa','Caminar al amanecer']) await expect(page.getByText(x,{exact:true})).toBeVisible()
  await page.getByText('Explorar',{exact:true}).click()
  await expect(page.getByRole('heading',{name:'Explorar el Territorio'})).toBeVisible()
  for(const x of ['Bienestar físico y mental','Trabajo y propósito','Relaciones','Familia y hogar','Desarrollo personal','Creatividad','Comunidad y servicio','Entorno y naturaleza','Finanzas y recursos']) await expect(page.getByRole('button',{name:x,exact:true})).toBeVisible()
  await page.getByText('Comunidad',{exact:true}).click()
  await expect(page.getByRole('heading',{name:'Impacto y Aprendizaje'})).toBeVisible()
  await expect(page.getByText('Tu camino no solo transforma tu vida. También ilumina el camino de otros.')).toBeVisible()
 })
 test('chrome stays fixed to five canonical destinations',async({page})=>{
   for(const x of ['Inicio','Explorar','Mi Vida','Comunidad','Biblioteca']) await expect(page.getByText(x,{exact:true})).toBeVisible()
 })
 test('prototype renders at mobile viewport without horizontal overflow',async({page})=>{
   await page.setViewportSize({width:390,height:844})
   const dims=await page.evaluate(()=>({sw:document.documentElement.scrollWidth,cw:document.documentElement.clientWidth}))
   expect(dims.sw).toBeLessThanOrEqual(dims.cw)
 })
})
